from typing import List
from fastapi import APIRouter, Depends, HTTPException, status, Query
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.hospital import Hospital
from app.models.delivery import DeliveryEstimate
from app.models.user import User
from app.schemas.delivery import (
    RouteCalculationRequest, RouteCalculationResponse, DeliveryEstimateResponse
)
from app.auth.security import get_current_active_user
from app.services.delivery_service import calculate_route_async

router = APIRouter(prefix="/api/delivery", tags=["Delivery & Routing"])


@router.post("/calculate-route", response_model=RouteCalculationResponse)
async def calculate_route(
    data: RouteCalculationRequest,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """
    Calculate real-time road distance, driving duration, and logistics cost
    between two hospitals using OSRM routing with fallback to Haversine.
    """
    if data.source_hospital_id == data.destination_hospital_id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Source and destination hospitals cannot be identical"
        )

    src = db.query(Hospital).filter(Hospital.id == data.source_hospital_id).first()
    if not src:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Source hospital not found")

    dst = db.query(Hospital).filter(Hospital.id == data.destination_hospital_id).first()
    if not dst:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Destination hospital not found")

    res = await calculate_route_async(
        lat1=src.latitude,
        lon1=src.longitude,
        lat2=dst.latitude,
        lon2=dst.longitude,
        db=db
    )

    return RouteCalculationResponse(
        source_hospital_id=src.id,
        destination_hospital_id=dst.id,
        source_hospital_name=src.name,
        destination_hospital_name=dst.name,
        distance_km=res["distance_km"],
        estimated_duration_hours=res["duration_hours"],
        is_road_distance=res["is_road_distance"],
        cost_per_km=res["cost_per_km"],
        fixed_charge=res["fixed_charge"],
        estimated_cost=res["estimated_cost"],
        route_geometry=res.get("geometry", []),
    )


@router.get("/estimates", response_model=List[DeliveryEstimateResponse])
def list_delivery_estimates(
    skip: int = Query(0, ge=0),
    limit: int = Query(50, ge=1, le=200),
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """List historical delivery estimates generated by the system."""
    estimates = db.query(DeliveryEstimate).order_by(DeliveryEstimate.created_at.desc()).offset(skip).limit(limit).all()
    return estimates
